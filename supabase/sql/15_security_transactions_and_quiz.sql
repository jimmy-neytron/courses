create or replace function public.reorder_course_tree(
  p_course_id uuid,
  p_modules jsonb,
  p_lessons jsonb
)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  perform 1
  from public.courses
  where id = p_course_id
    and owner_id = auth.uid()
  for update;

  if not found then
    raise exception 'course_owner_required'
      using errcode = '42501';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(
      coalesce(p_modules, '[]'::jsonb)
    ) as item(id uuid, position integer)
    where not exists (
      select 1
      from public.course_modules m
      where m.id = item.id
        and m.course_id = p_course_id
    )
  ) then
    raise exception 'invalid_module_order_payload'
      using errcode = '22023';
  end if;

  if exists (
    select 1
    from jsonb_to_recordset(
      coalesce(p_lessons, '[]'::jsonb)
    ) as item(id uuid, module_id uuid, position integer)
    where not exists (
      select 1
      from public.lessons l
      join public.course_modules m
        on m.id = item.module_id
       and m.course_id = p_course_id
      where l.id = item.id
        and l.course_id = p_course_id
    )
  ) then
    raise exception 'invalid_lesson_order_payload'
      using errcode = '22023';
  end if;

  update public.course_modules m
  set
    position = item.position,
    updated_at = now()
  from jsonb_to_recordset(
    coalesce(p_modules, '[]'::jsonb)
  ) as item(id uuid, position integer)
  where m.id = item.id
    and m.course_id = p_course_id;

  update public.lessons l
  set
    module_id = item.module_id,
    position = item.position,
    updated_at = now()
  from jsonb_to_recordset(
    coalesce(p_lessons, '[]'::jsonb)
  ) as item(id uuid, module_id uuid, position integer)
  where l.id = item.id
    and l.course_id = p_course_id;
end;
$$;

revoke all on function public.reorder_course_tree(uuid, jsonb, jsonb)
  from public;
