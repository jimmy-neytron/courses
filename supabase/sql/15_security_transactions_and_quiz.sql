create or replace function public.publish_course(
  p_course_id uuid,
  p_changelog text default 'Published from Course Platform'
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_course public.courses%rowtype;
  v_release_id uuid;
  v_version integer;
  v_published_at timestamptz := now();
  v_module_count integer;
  v_lesson_count integer;
  v_snapshot jsonb;
begin
  if auth.uid() is null then
    raise exception 'authentication_required'
      using errcode = '42501';
  end if;

  select *
  into v_course
  from public.courses
  where id = p_course_id
  for update;

  if not found then
    raise exception 'course_not_found'
      using errcode = 'P0002';
  end if;

  if v_course.owner_id <> auth.uid() then
    raise exception 'course_owner_required'
      using errcode = '42501';
  end if;

  update public.lessons
  set
    status = 'published',
    published_at = v_published_at,
    updated_at = v_published_at
  where course_id = p_course_id;

  update public.course_modules
  set
    is_published = true,
    updated_at = v_published_at
  where course_id = p_course_id;

  update public.courses
  set
    status = 'published',
    visibility = 'public',
    published_at = v_published_at,
    updated_at = v_published_at
  where id = p_course_id;

  select coalesce(max(r.version), 0) + 1
  into v_version
  from public.course_releases r
  where r.course_id = p_course_id;

  select count(*)
  into v_module_count
  from public.course_modules
  where course_id = p_course_id;

  select count(*)
  into v_lesson_count
  from public.lessons
  where course_id = p_course_id;

  v_snapshot := jsonb_build_object(
    'schemaVersion', 1,
    'publishedAt', v_published_at,
    'course', public.build_course_tree_json(
      p_course_id,
      false
    )
  );

  insert into public.course_releases (
    course_id,
    version,
    snapshot,
    module_count,
    lesson_count,
    changelog,
    published_by,
    published_at
  )
  values (
    p_course_id,
    v_version,
    v_snapshot,
    v_module_count,
    v_lesson_count,
    nullif(trim(coalesce(p_changelog, '')), ''),
    auth.uid(),
    v_published_at
  )
  returning id into v_release_id;

  update public.courses
  set current_release_id = v_release_id
  where id = p_course_id;

  return v_release_id;
end;
$$;

revoke all on function public.publish_course(uuid, text) from public;
grant execute on function public.publish_course(uuid, text)
  to authenticated;

