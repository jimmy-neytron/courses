  select *
  into v_source
  from public.course_modules
  where id = p_module_id;

  if not found then
    raise exception 'module_not_found'
      using errcode = 'P0002';
  end if;

  perform 1
  from public.courses
  where id = v_source.course_id
    and owner_id = auth.uid()
