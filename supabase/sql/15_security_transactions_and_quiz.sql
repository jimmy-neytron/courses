-- ============================================================================
-- Course Platform: security, transactional commands and safe quiz verification
-- Apply this migration in Supabase SQL Editor AFTER a database backup.
--
-- Designed for the current owner/public production model:
-- - courses.owner_id identifies the author;
-- - published public courses can be viewed by guests;
-- - lesson_blocks.private_content must never be selected by learners;
-- - frontend mutations use the RPC functions declared below.
-- ============================================================================

begin;

-- ----------------------------------------------------------------------------
-- Storage cleanup outbox
-- PostgreSQL and Supabase Storage do not share one transaction. Destructive
-- RPCs enqueue file paths in the same DB transaction. The frontend removes the
-- objects only after the DB command succeeds and acknowledges successful paths.
-- ----------------------------------------------------------------------------

create table if not exists public.storage_cleanup_queue (
  id bigint generated by default as identity primary key,
  bucket_id text not null default 'lesson-assets',
  object_path text not null,
  requested_by uuid,
  status text not null default 'pending'
    check (status in ('pending', 'completed')),
  attempts integer not null default 0 check (attempts >= 0),
  last_error text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  unique (bucket_id, object_path)
);

alter table public.storage_cleanup_queue
  add column if not exists requested_by uuid;

alter table public.storage_cleanup_queue enable row level security;
revoke all on table public.storage_cleanup_queue from anon, authenticated;

create index if not exists storage_cleanup_queue_pending_idx
  on public.storage_cleanup_queue(status, created_at)
  where status = 'pending';

create or replace function public.enqueue_lesson_assets(
  p_block_ids uuid[]
)
returns void
language sql
security definer
set search_path = public
as $$
  insert into public.storage_cleanup_queue (
    bucket_id,
    object_path,
    requested_by,
    status,
    attempts,
    last_error,
    completed_at
  )
  select
    'lesson-assets',
    asset.object_path,
    auth.uid(),
    'pending',
    0,
    null,
    null
  from (
    select nullif(b.public_content ->> 'audioPath', '') as object_path
    from public.lesson_blocks b
    where b.id = any(coalesce(p_block_ids, array[]::uuid[]))

    union

    select nullif(b.public_content ->> 'filePath', '') as object_path
    from public.lesson_blocks b
    where b.id = any(coalesce(p_block_ids, array[]::uuid[]))
  ) asset
  where asset.object_path is not null
  on conflict (bucket_id, object_path)
  do update set
    requested_by = auth.uid(),
    status = 'pending',
    attempts = 0,
    last_error = null,
    completed_at = null;
$$;

revoke all on function public.enqueue_lesson_assets(uuid[]) from public;

create or replace function public.ack_storage_cleanup(
  p_paths text[]
)
returns void
language sql
security definer
set search_path = public
as $$
  update public.storage_cleanup_queue
  set
    status = 'completed',
    completed_at = now(),
    last_error = null
  where bucket_id = 'lesson-assets'
    and requested_by = auth.uid()
    and object_path = any(coalesce(p_paths, array[]::text[]));
$$;

revoke all on function public.ack_storage_cleanup(text[]) from public;
grant execute on function public.ack_storage_cleanup(text[]) to authenticated;

-- ----------------------------------------------------------------------------
-- Course tree delivery
-- Direct learner SELECT on lesson_blocks is disabled below. This function
-- returns private_content only to the course owner.
-- ----------------------------------------------------------------------------

create or replace function public.build_course_tree_json(
  p_course_id uuid,
  p_include_private boolean
)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select
    to_jsonb(c)
    || jsonb_build_object(
      'owner',
      coalesce(
        (
          select jsonb_build_object(
            'id', p.id,
            'display_name', p.display_name,
            'avatar_url', p.avatar_url
          )
          from public.profiles p
          where p.id = c.owner_id
        ),
        '{}'::jsonb
      ),
      'course_modules',
      coalesce(
        (
          select jsonb_agg(
            to_jsonb(m)
            || jsonb_build_object(
              'lessons',
              coalesce(
                (
                  select jsonb_agg(
                    to_jsonb(l)
                    || jsonb_build_object(
                      'lesson_blocks',
                      coalesce(
                        (
                          select jsonb_agg(
                            case
                              when p_include_private then to_jsonb(b)
                              else
                                (to_jsonb(b) - 'private_content')
                                || jsonb_build_object(
                                  'private_content',
                                  '{}'::jsonb
                                )
                            end
                            order by b.position, b.id
                          )
                          from public.lesson_blocks b
                          where b.lesson_id = l.id
                        ),
                        '[]'::jsonb
                      )
                    )
                    order by l.position, l.id
                  )
                  from public.lessons l
                  where l.module_id = m.id
                    and (
                      p_include_private
                      or l.status = 'published'
                    )
                ),
                '[]'::jsonb
              )
            )
            order by m.position, m.id
          )
          from public.course_modules m
          where m.course_id = c.id
            and (
              p_include_private
              or m.is_published
            )
        ),
        '[]'::jsonb
      )
    )
  from public.courses c
  where c.id = p_course_id;
$$;

revoke all on function public.build_course_tree_json(uuid, boolean)
  from public;

create or replace function public.get_course_tree(
  p_course_id uuid
)
returns jsonb
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_owner_id uuid;
  v_status text;
  v_visibility text;
  v_include_private boolean;
begin
  select
    c.owner_id,
    c.status::text,
    c.visibility::text
  into
    v_owner_id,
    v_status,
    v_visibility
  from public.courses c
  where c.id = p_course_id;

  if not found then
    return null;
  end if;

  v_include_private := auth.uid() is not null
    and auth.uid() = v_owner_id;

  if not v_include_private
    and not (
      v_status = 'published'
      and v_visibility in ('public', 'unlisted')
    )
  then
    raise exception 'course_not_accessible'
      using errcode = '42501';
  end if;

  return public.build_course_tree_json(
    p_course_id,
    v_include_private
  );
end;
$$;

revoke all on function public.get_course_tree(uuid) from public;
grant execute on function public.get_course_tree(uuid)
  to anon, authenticated;

-- ----------------------------------------------------------------------------
-- Quiz verification
-- The correct option and author explanation remain server-side.
-- ----------------------------------------------------------------------------

create or replace function public.check_lesson_block_answer(
  p_block_id uuid,
  p_option_index integer
)
returns table (
  correct boolean,
  explanation text
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  v_course_id uuid;
  v_lesson_status text;
  v_course_status text;
  v_visibility text;
  v_owner_id uuid;
  v_correct_option integer;
  v_explanation text;
begin
  select
    b.course_id,
    l.status::text,
    c.status::text,
    c.visibility::text,
    c.owner_id,
    case
      when jsonb_typeof(b.private_content -> 'correctOption') = 'number'
      then (b.private_content ->> 'correctOption')::integer
      else null
    end,
    coalesce(b.private_content ->> 'explanation', '')
  into
    v_course_id,
    v_lesson_status,
    v_course_status,
    v_visibility,
    v_owner_id,
    v_correct_option,
    v_explanation
  from public.lesson_blocks b
  join public.lessons l on l.id = b.lesson_id
  join public.courses c on c.id = b.course_id
  where b.id = p_block_id
    and b.block_type = 'single_choice';

  if not found then
    raise exception 'quiz_block_not_found'
      using errcode = 'P0002';
  end if;

  if not (
    coalesce(auth.uid() = v_owner_id, false)
    or (
      v_course_status = 'published'
      and v_lesson_status = 'published'
      and v_visibility in ('public', 'unlisted')
    )
  )
  then
    raise exception 'quiz_block_not_accessible'
      using errcode = '42501';
  end if;

  return query
  select
    coalesce(p_option_index = v_correct_option, false),
    v_explanation;
end;
$$;

revoke all on function public.check_lesson_block_answer(uuid, integer)
  from public;
grant execute on function public.check_lesson_block_answer(uuid, integer)
  to anon, authenticated;

