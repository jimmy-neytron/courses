create or replace function public.duplicate_lesson(
  p_lesson_id uuid,
  p_target_module_id uuid,
  p_position integer,
  p_title text
)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_source public.lessons%rowtype;
  v_course_id uuid;
  v_new_lesson_id uuid;
begin
  select *
  into v_source
  from public.lessons
  where id = p_lesson_id;

  if not found then
    raise exception 'lesson_not_found'
      using errcode = 'P0002';
  end if;

  v_course_id := v_source.course_id;

  perform 1
  from public.courses
  where id = v_course_id
    and owner_id = auth.uid()
  for update;

  if not found then
    raise exception 'course_owner_required'
      using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.course_modules
    where id = p_target_module_id
      and course_id = v_course_id
  ) then
    raise exception 'target_module_not_found'
      using errcode = '22023';
  end if;

  update public.lessons
  set position = position + 1
  where module_id = p_target_module_id
    and position >= greatest(p_position, 0);

  insert into public.lessons (
    course_id,
    module_id,
    slug,
    title,
    description,
    objectives,
    duration_minutes,
    passing_score,
    position,
    status,
    is_preview
  )
  values (
    v_course_id,
    p_target_module_id,
    'lesson-' || replace(gen_random_uuid()::text, '-', ''),
    coalesce(nullif(trim(p_title), ''), v_source.title || ' — копия'),
    v_source.description,
    v_source.objectives,
    v_source.duration_minutes,
    v_source.passing_score,
    greatest(p_position, 0),
    'draft',
    false
  )
  returning id into v_new_lesson_id;

  insert into public.lesson_blocks (
    course_id,
    lesson_id,
    block_type,
    position,
    title,
    public_content,
    private_content,
    settings,
    is_required,
    points,
    schema_version
  )
  select
    v_course_id,
    v_new_lesson_id,
    b.block_type,
    b.position,
    b.title,
    b.public_content
      - 'audioPath'
      - 'filePath'
      - 'fileName'
      - 'fileSize',
    b.private_content,
    b.settings,
    b.is_required,
    b.points,
    b.schema_version
  from public.lesson_blocks b
  where b.lesson_id = p_lesson_id
  order by b.position, b.id;

  return v_new_lesson_id;
end;
$$;

revoke all on function public.duplicate_lesson(uuid, uuid, integer, text)
  from public;
grant execute on function public.duplicate_lesson(uuid, uuid, integer, text)
  to authenticated;

create or replace function public.duplicate_module(
  p_module_id uuid,
  p_position integer,
  p_title text
