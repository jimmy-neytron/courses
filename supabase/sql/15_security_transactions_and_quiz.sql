as $$
declare
  v_block_ids uuid[];
begin
  perform 1
  from public.courses
  where id = p_course_id
    and owner_id = auth.uid()
  for update;

  if not found then
    raise exception 'course_owner_required'
      using errcode = '42501';
  end if;

  if exists (
    select 1
    from unnest(
      coalesce(p_lesson_ids, array[]::uuid[])
    ) as item(lesson_id)
    where not exists (
      select 1
      from public.lessons l
      where l.id = item.lesson_id
        and l.course_id = p_course_id
    )
  ) then
    raise exception 'invalid_lesson_delete_payload'
      using errcode = '22023';
  end if;

  select coalesce(array_agg(b.id), array[]::uuid[])
  into v_block_ids
  from public.lesson_blocks b
  where b.lesson_id = any(
    coalesce(p_lesson_ids, array[]::uuid[])
  );

  perform public.enqueue_lesson_assets(v_block_ids);

  delete from public.lessons
  where course_id = p_course_id
    and id = any(coalesce(p_lesson_ids, array[]::uuid[]));
end;
$$;

revoke all on function public.delete_lessons(uuid, uuid[]) from public;
grant execute on function public.delete_lessons(uuid, uuid[])
  to authenticated;

create or replace function public.delete_course(
  p_course_id uuid
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_block_ids uuid[];
begin
  perform 1
  from public.courses
  where id = p_course_id
    and owner_id = auth.uid()
  for update;

  if not found then
    raise exception 'course_owner_required'
      using errcode = '42501';
  end if;

  select coalesce(array_agg(b.id), array[]::uuid[])
  into v_block_ids
  from public.lesson_blocks b
  where b.course_id = p_course_id;

  perform public.enqueue_lesson_assets(v_block_ids);

  update public.courses
  set current_release_id = null
  where id = p_course_id;

  delete from public.courses
  where id = p_course_id;
end;
$$;

revoke all on function public.delete_course(uuid) from public;
grant execute on function public.delete_course(uuid)
  to authenticated;

